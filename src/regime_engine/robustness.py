# Model selection beyond K = 3
# ---------------------------------------------------------------------------

#: K values the paper reports. K=2 and K=3 are the main comparison; K=4 and K=5
#: check whether more states are supported and whether such models can be
#: estimated stably. On this sample they can: all four converge from 40 starts.
SELECTION_KS = (2, 3, 4, 5)

#: More starts than the K<=3 default. The extra states multiply the local optima,
#: and a K=4 result from a handful of starts would not be worth reporting.
SELECTION_N_STARTS = 40
SELECTION_N_ITER = 300


def n_free_parameters(K: int) -> int:
    """``|theta_K| = K^2 + 2K - 1``, the count stated with the Gaussian HMM in Section 2.1."""
    return K * K + 2 * K - 1


def preferred_k(records):
    """The K with the lowest finite BIC; ties go to the smaller K."""
    usable = [r for r in records
              if r.get("BIC") is not None and np.isfinite(r["BIC"])]
    if not usable:
        return None
    return min(usable, key=lambda r: (r["BIC"], r["K"]))["K"]


def model_selection(r, ks=SELECTION_KS, *, n_starts: int = SELECTION_N_STARTS,
                    n_iter: int = SELECTION_N_ITER, seed_base: int = HMM_SEED,
                    reference: int = 2, verbose: bool = False) -> list[dict]:
    """Fit one Gaussian HMM per K and return their information criteria.

    ``r`` is passed through unscaled. Log-likelihoods are not scale-free, so the
    absolute figures depend on the units of ``r``; the differences reported as
    ``delta_BIC`` do not, because a change of units shifts every row by the same
    constant.
    """
    r = np.asarray(r, dtype=float)
    out = []
    for K in ks:
        hmm = GaussianHMM(K=K, n_starts=n_starts, n_iter=n_iter,
                          random_state=seed_base + K).fit(r)
        rec = {
            "K": int(K),
            "logL": float(hmm.log_likelihood_),
            "n_params": n_free_parameters(K),
            "AIC": float(hmm.aic()),
            "BIC": float(hmm.bic(len(r))),
            "sigma_bps_per_hour": sorted(float(s) * 1e4 for s in hmm.sigma),
            "seed": int(seed_base + K),
        }
        out.append(rec)
        if verbose:
            print(f"  K={K}  logL={rec['logL']:12.2f}  BIC={rec['BIC']:12.2f}  "
                  f"sigma={[round(s, 1) for s in rec['sigma_bps_per_hour']]}",
                  flush=True)

    base = next((x["BIC"] for x in out if x["K"] == reference), None)
    for rec in out:
        rec["delta_BIC"] = None if base is None else rec["BIC"] - base
    return out
