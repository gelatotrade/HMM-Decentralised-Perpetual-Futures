# table3b: the paper-window fit
# ---------------------------------------------------------------------------
def _funding(diag: dict, times=None) -> str:
    b = msar_block(diag, "paper window")
    inf = b["inference"]
    h, r = inf["hessian"], inf["robust"]
    tau = b["half_life_hours"]
    sw = b["half_life_switching_hours"]
    swi = b["half_life_switching_interp_hours"]

    def pair(values, digits):
        return " & ".join(fmt_num(v, digits) for v in values)

    def se_pair(key, digits):
        return " & ".join(f"({fmt_num(h[key][k], digits)}; {fmt_num(r[key][k], digits)})"
                          for k in range(2))

    def t_pair():
        return " & ".join(f"{fmt_num(h['phi_t_unit'][k], 2)}; {fmt_num(r['phi_t_unit'][k], 2)}"
                          for k in range(2))

    rows = [
        f"$\\hat\\mu_k$ (bps) & {pair(b['mu_bps'], 2)} \\\\",
        f"$\\hat\\sigma_k$ (bps) & {pair(b['sigma_bps'], 3)} \\\\",
        f"$\\hat\\phi_k$ & {pair(b['phi'], 4)} \\\\",
        f"\\quad s.e.\\ (Hessian; sandwich) & {se_pair('phi_se', 4)} \\\\",
        f"\\quad $t$ against unity (Hessian; sandwich) & {t_pair()} \\\\",
        f"$\\hat p_{{kk}}$ & {pair(b['p_stay'], 3)} \\\\",
        f"\\quad s.e.\\ (Hessian; sandwich) & {se_pair('p_stay_se', 3)} \\\\",
        "Expected duration $1/(1-\\hat p_{kk})$ (h) & "
        f"{pair(b['expected_duration_hours'], 1)} \\\\",
        f"Stationary share & {pair(b['stationary_share'], 3)} \\\\",
        "\\addlinespace",
        f"Half-life within the regime, $\\hat\\tau_k$ (h) & {pair(tau, 1)} \\\\",
        "\\quad 95\\% CI from $\\hat\\phi_k$, Hessian & "
        + " & ".join(fmt_hl_ci(c) for c in h["half_life_ci95_from_phi"]) + " \\\\",
        "\\quad 95\\% CI from $\\hat\\phi_k$, sandwich & "
        + " & ".join(fmt_hl_ci(c) for c in r["half_life_ci95_from_phi"]) + " \\\\",
        f"Half-life under switching, $\\hat\\tau^{{\\text{{sw}}}}_k$ (h) & {_hours(sw[0])} & "
        f"{_hours(sw[1])} \\\\",
        f"\\quad interpolated & {pair(swi, 1)} \\\\",
        "\\midrule",
        "Half-life ratio & Hessian & Sandwich \\\\",
        "\\midrule",
        f"$\\hat R = \\hat\\tau_{{\\text{{calm}}}}/\\hat\\tau_{{\\text{{stressed}}}} = "
        f"{b['half_life_ratio']:.2f}$, s.e. & {fmt_num(h['ratio_se'], 2)} & "
        f"{fmt_num(r['ratio_se'], 2)} \\\\",
    ]
    wald = {cov: inf[cov]["ratio_wald"] for cov in COVS}
    rows += [
        "\\quad Wald test of $\\phi_{\\text{calm}} = \\phi_{\\text{stressed}}$: $z$ ($p$) & "
        + " & ".join(f"{fmt_num(wald[c]['z'], 2)} ({fmt_p(wald[c]['p'])})" for c in COVS)
        + " \\\\",
        "\\quad side of unity & "
        + " & ".join(fmt_side(wald[c]["significance"]) for c in COVS) + " \\\\",
    ]
    for form, name in (("linear", "linear"), ("log", "log scale"), ("fieller", "Fieller")):
        rows.append(f"\\quad 95\\% CI, {name} & {fmt_set(h['ratio_ci95'][form])} & "
                    f"{fmt_set(r['ratio_ci95'][form])} \\\\")
    rows += [
        # the ratio of the unrounded interpolated hours; their rounded values,
        # printed above, need not divide to it
        f"$\\hat R^{{\\text{{sw}}}} = {b['ratio_switching_interp']:.2f}$ (interpolated; "
        f"whole hours {sw[0]}/{sw[1]}), s.e. & "
        f"{fmt_num(h['ratio_switching_interp_se'], 2)} & "
        f"{fmt_num(r['ratio_switching_interp_se'], 2)} \\\\",
        "\\quad side of unity & "
        + " & ".join(fmt_side(inf[c]["ratio_switching_side"]) for c in COVS) + " \\\\",
        f"\\quad 95\\% CI, log scale & {fmt_set(h['ratio_switching_interp_ci95']['log'])} & "
        f"{fmt_set(r['ratio_switching_interp_ci95']['log'])} \\\\",
        "\\quad 95\\% interval, simulated & "
        + " & ".join(fmt_sim(inf[c]["ratio_switching_sim"]["ci95"]) for c in COVS) + " \\\\",
        f"$\\hat p_{{cc}} + \\hat p_{{ss}} - 1 = {b['chain_eigenvalue']:.3f}$, s.e. & "
        f"{fmt_num(h['chain_eigenvalue_se'], 3)} & {fmt_num(r['chain_eigenvalue_se'], 3)} \\\\",
    ]
    opg = inf["opg"]["ratio_se"]
    n_obs = f"{b['n_obs']:,}".replace(",", "{,}")
    logl = f"{b['logL']:,.2f}".replace(",", "{,}")
    foot = (
        f"\\multicolumn{{3}}{{l}}{{\\footnotesize $\\log\\mathcal{{L}} = "
        f"{logl}$, $T_{{\\text{{eff}}}} = {n_obs}$; "
        f"s.e.\\ of $\\hat R$ from the outer product of gradients: {opg:.2f}}} \\\\"
    )
    top = b.get("ratio_sandwich_top_hours")
    if top:
        t = times[top[0]["index"]] if times is not None else None
        # A funding record is stamped at settlement: the record stamped t
        # carries the premium averaged over the hour before t.
        record = "a record" if t is None else (
            f"the record stamped {t.day} {t:%b %Y %H:%M} UTC (premium averaged over "
            f"{t - pd.Timedelta(hours=1):%H:%M}--{t:%H:%M})")
        foot += (
            "\n\\multicolumn{3}{l}{\\footnotesize Largest single-hour share of the sandwich "
            f"variance of $\\hat R$: {100 * top[0]['share']:.1f}\\%, "
            f"next largest {100 * top[1]['share']:.1f}\\%. It belongs to}} \\\\"
            f"\n\\multicolumn{{3}}{{l}}{{\\footnotesize {record}, with}} \\\\"
            f"\n\\multicolumn{{3}}{{l}}{{\\footnotesize $y_t = {top[0]['y']:.2f}$ bps "
            f"after ${top[0]['y_prev']:+.2f}$ bps an hour earlier.}} \\\\"
        )
    return (
        _BANNER
        + "% Paper window 2 Oct 2025 -- 28 Apr 2026. Source: output/diagnostics.json, the msar\n"
          "% block whose window name contains 'paper window'. Standard errors in parentheses,\n"
          "% Hessian first, sandwich second. Half-life intervals transform phi_k's Wald\n"
          "% interval; an upper end at infinity means that interval reaches a unit root.\n"
          "% The switching-adjusted half-life is the first hour at which e_k'(P o Phi)^h 1\n"
          "% falls to one half, interpolated log-linearly; R^sw is the ratio of the\n"
          "% interpolated hours (whole hours in brackets). Its log-scale interval is the delta\n"
          "% method; the simulated one takes the 2.5% and 97.5% quantiles over 50,000 draws\n"
          "% of (p[0->0], p[1->0], phi_0, phi_1) from their asymptotic normal distribution,\n"
          "% the probabilities on the logit scale. An end at 0.00 or infinity comes from draws\n"
          "% whose expected path does not halve within 10,000 hours (an unbounded half-life).\n"
          "% The side of unity of R is the Wald test of phi_calm = phi_stressed (R = 1 exactly\n"
          "% when they are equal); R^sw takes the same verdict because p_cc + p_ss - 1 > 0\n"
          "% significantly. The linear, log-scale and Fieller sets are descriptive.\n"
        + "\\begin{tabular}{@{}lcc@{}}\n\\toprule\n & Calm & Stressed \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\midrule\n" + foot + "\n\\bottomrule\n\\end{tabular}\n"
    )


