# ---------------------------------------------------------------------------
# Formatting
# ---------------------------------------------------------------------------
def fmt_num(x, digits: int = 2) -> str:
    """A number for a LaTeX cell, with a typographic minus; ``--`` for a missing one."""
    if x is None:
        return "--"
    s = f"{abs(x):,.{digits}f}".replace(",", "{,}")
    return f"$-{s}$" if x < 0 and float(f"{x:.{digits}f}") != 0 else s


def _bound(x, digits: int) -> str:
    """An interval end; one more decimal when it would otherwise print as exactly 1."""
    if x != 1.0 and round(abs(x), digits) == 1.0:
        digits += 1
    return fmt_num(x, digits)


def fmt_set(form: dict, digits: int = 2) -> str:
    """A confidence set as printed: bounded, two rays, the whole line, or ``--``."""
    lo, hi = form.get("bounds") or (None, None)
    shape = form.get("shape")
    if shape == "bounded" and lo is not None and hi is not None:
        return f"[{_bound(lo, digits)}, {_bound(hi, digits)}]"
    if shape == "two_rays" and lo is not None and hi is not None:
        return f"$(-\\infty, {lo:.{digits}f}] \\cup [{hi:.{digits}f}, \\infty)$"
    if shape == "whole_line":
        return "$(-\\infty, \\infty)$"
    return "--"


def fmt_side(significance: str) -> str:
    return {"above": "$>1$", "below": "$<1$", "ns": "n.s."}.get(significance, "--")


def fmt_p(p) -> str:
    """A two-sided p-value: ``$<$0.001``, three decimals below 0.1, two above."""
    if p is None:
        return "--"
    if p < 0.001:
        return "$<$0.001"
    if p < 0.0995:
        return f"{p:.3f}"
    return f"{p:.2f}"


def fmt_sim(ci, digits: int = 2) -> str:
    """A simulated interval; an upper end of ``None`` is unbounded."""
    lo, hi = (None, None) if not ci else (ci[0], ci[1])
    if lo is None:
        return "--"
    if hi is None:
        return f"[{fmt_num(lo, digits)}, $\\infty$)"
    return f"[{_bound(lo, digits)}, {_bound(hi, digits)}]"


def fmt_hl_ci(ci) -> str:
    """A half-life interval; an upper end of ``None`` is unbounded."""
    lo, hi = ci
    left = "--" if lo is None else f"{lo:.{2 if lo < 10 else 1}f}"
    right = "$\\infty$)" if hi is None else f"{hi:.{2 if hi < 10 else 1}f}]"
    return f"[{left}, {right}"


def _hours(h) -> str:
    return "--" if h is None else f"{int(h)}"


# ---------------------------------------------------------------------------
# Locating the records
# ---------------------------------------------------------------------------
def msar_block(diag: dict, which: str) -> dict:
    """The MS-AR record of ``diagnostics.json`` whose window name contains ``which``."""
    hits = [b["msar"] for b in diag["tests"] if "msar" in b and which in b["msar"]["window"]]
    if len(hits) != 1:
        raise KeyError(f"expected one MS-AR block matching {which!r}, found {len(hits)}")
    return hits[0]


def injection_dates(oos: dict, premium_path=DEFAULT_PREMIUM_FULL) -> list:
    """The hours the injection variants overwrite, as timestamps."""
    prem = pd.read_csv(premium_path, usecols=["time"])
    times = pd.to_datetime(prem["time"], utc=True, format="ISO8601")
    times = times.drop_duplicates().sort_values().reset_index(drop=True)
    after = times[times > pd.Timestamp(PAPER_WINDOW[1])].reset_index(drop=True)
    return [after[int(r["variant"].split("@")[1])] for r in oos["injection"][1:]]


def paper_window_times(premium_path=DEFAULT_PREMIUM_FULL) -> list:
    """The stamps of the paper-window premium, aligned to ``panel.load_paper_window_premium``."""
    df = pd.read_csv(premium_path, usecols=["time"])
    times = pd.to_datetime(df["time"], utc=True)
    start, end = PAPER_WINDOW
    return list(times[(times >= start) & (times <= end)])


def _day(t) -> str:
    return f"{t.day} {t:%b %Y}"


