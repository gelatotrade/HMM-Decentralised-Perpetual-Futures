def sheet_rows(oos: dict, diag: dict) -> list:
    """Every MS-AR fit with R, R^sw, the Wald verdicts and each interval form's side."""
    recs = [("paper window (diagnostics)", msar_block(diag, "paper window")),
            ("sub-period (diagnostics)", msar_block(diag, "sub-sample")),
            ("whole series", oos["extended_window"]),
            ("later window", oos["injection"][0])]
    recs += [(f"rolling {r['index']:2d} mid {str(r['mid'])[:10]}", r) for r in oos["rolling"]]
    recs += [(f"sensitivity {r['variant']}", r) for r in oos["sensitivity"]]
    recs += [(f"injection {r['variant']}", r) for r in oos["injection"][1:]]
    rows = []
    for label, rec in recs:
        row = {
            "label": label,
            "ratio": rec.get("ratio", rec.get("half_life_ratio")),
            "ratio_switching": rec["ratio_switching"],
            "half_life_switching_hours": rec["half_life_switching_hours"],
            "half_life_switching_interp_hours": rec["half_life_switching_interp_hours"],
            "ratio_switching_interp": rec["ratio_switching_interp"],
            "chain_eigenvalue": rec["chain_eigenvalue"],
        }
        for cov in COVS:
            inf = rec["inference"][cov]
            ci = inf["ratio_ci95"]
            row[cov] = {form: ci[form]["significance"] for form in FORMS}
            row[f"{cov}_excludes_unity"] = [f for f in FORMS
                                            if ci[f]["significance"] in ("above", "below")]
            row[f"{cov}_switching_log"] = inf["ratio_switching_interp_ci95"]["log"]["significance"]
            wald = inf["ratio_wald"]
            row[f"{cov}_wald"] = {"z": wald["z"], "p": wald["p"], "side": wald["significance"]}
            row[f"{cov}_switching_side"] = inf["ratio_switching_side"]
            row[f"{cov}_switching_sim"] = inf["ratio_switching_sim"]["ci95"]
            row[f"{cov}_chain_eigenvalue_se"] = inf["chain_eigenvalue_se"]
        rows.append(row)
    return rows


def format_sheet(rows: list) -> str:
    """The numbers sheet as fixed-width text, one line per fit.

    Columns: R within the regime; R^sw from interpolated and from whole hours;
    the Wald test of phi_calm = phi_stressed (z, two-sided p, side) under the
    Hessian (H) and the sandwich (S), which also decides R^sw's side; R^sw's
    simulated 95% interval under the sandwich; and, for reference, the side of
    unity of the linear, log-scale and Fieller sets under each covariance.
    """
    def num(v, width, digits=2):
        return f"{'--':>{width}s}" if v is None else f"{v:{width}.{digits}f}"

    def wald(w):
        p = "--" if w["p"] is None else f"{w['p']:.4f}"
        return f"{num(w['z'], 6)} {p:>6s} {w['side']:>5s}"

    def sim(ci):
        lo, hi = ci
        return f"[{num(lo, 5)}, {'inf' if hi is None else f'{hi:.2f}':>5s}]"

    head = (f"{'fit':34s} {'R':>7s} {'R_sw':>5s} {'R_sw_h':>6s} {'h_sw':>7s}  "
            f"{'Wald H: z, p, side':>20s}  {'Wald S: z, p, side':>20s}  "
            f"{'R_sw 95% sim S':>14s}  {'H lin/log/F':>17s}  {'S lin/log/F':>17s}")
    out = [head, "-" * len(head)]
    for r in rows:
        hs = "/".join(_hours(v) for v in r["half_life_switching_hours"])
        out.append(
            f"{r['label']:34s} {num(r['ratio'], 7)} {num(r['ratio_switching_interp'], 5)} "
            f"{num(r['ratio_switching'], 6)} {hs:>7s}  {wald(r['hessian_wald']):>20s}  "
            f"{wald(r['robust_wald']):>20s}  {sim(r['robust_switching_sim']):>14s}  "
            f"{'/'.join(r['hessian'][f] for f in FORMS):>17s}  "
            f"{'/'.join(r['robust'][f] for f in FORMS):>17s}")
    return "\n".join(out)


def _load(out_dir) -> tuple:
    out_dir = pathlib.Path(out_dir)
    diag = json.loads((out_dir / "diagnostics.json").read_text())
    oos = json.loads((out_dir / "oos_robustness.json").read_text())
    return diag, oos


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python3 -m regime_engine.msar_tables",
                                 description=__doc__.splitlines()[0])
    ap.add_argument("--artifacts", default=str(DEFAULT_OUT),
                    help="directory holding diagnostics.json and oos_robustness.json")
    ap.add_argument("--sheet", action="store_true", help="print the numbers sheet only")
    args = ap.parse_args(argv)
    diag, oos = _load(args.artifacts)
    if args.sheet:
        print(format_sheet(sheet_rows(oos, diag)))
        return 0
    for path in write_tables(diag, oos):
        print(f"[msar_tables] wrote {path}")
    return 0


if __name__ == "__main__":      # pragma: no cover
    raise SystemExit(main())
