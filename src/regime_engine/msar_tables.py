"""Manuscript tables for the switching-aware MS-AR inference.

    PYTHONPATH=src python3 -m regime_engine.msar_tables            # write the tables
    PYTHONPATH=src python3 -m regime_engine.msar_tables --sheet    # print the numbers sheet

Reads ``output/diagnostics.json`` and ``output/oos_robustness.json`` -- the
records written by ``regime_engine.diagnostics`` and ``regime_engine.oos``,
which carry the keys of ``msar.msar_robust_inference`` -- and writes three
tables to ``output/tables/`` and ``paper/tables/``:

* ``table3b_funding_robust.tex``: the paper-window MS-AR with the fitted
  chain (staying probabilities, expected durations, stationary shares), the
  within-regime and switching-adjusted half-lives, Hessian and sandwich
  standard errors, the Wald test of phi_calm = phi_stressed that decides the
  half-life ratio's side of unity, and the ratio's linear, log-scale and
  Fieller intervals under both covariances;
* ``table8b_rolling_robust.tex``: the rolling windows with the ratio, the
  Wald test's p-value and side of unity under each covariance, and the
  switching-adjusted ratio with its simulated interval under the sandwich;
* ``table9b_sensitivity_robust.tex``: the same columns for the upper-tail
  variants of the paper window, the other windows, and the later window with
  one hour overwritten.

Every side-of-unity mark is the Wald test's (``msar.ratio_wald_test``): R = 1
exactly when phi_calm = phi_stressed, so the test needs no delta step. The
interval forms are descriptive; the log-scale one excludes unity too often
when phi_stressed's interval approaches one, which is why no verdict rests on
it. The switching-adjusted ratio takes the same verdict, since p_cc + p_ss - 1
is significantly positive in every fit (``msar.switching_ratio_side``).

Nothing here estimates anything; the tables only format the artifacts.
"""
