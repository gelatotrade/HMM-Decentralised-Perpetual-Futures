def _row_header(lead: list) -> str:
    """The three header lines, after the ``lead`` column titles.

    The Wald test's two covariances (p-value and side of unity each) share one
    spanning title, and the switching-adjusted ratio and its interval another.
    """
    n = len(lead) + 1                      # columns before the first Wald column
    wald = "\\multicolumn{4}{c}{Wald test of $\\phi_{\\text{calm}} = \\phi_{\\text{stressed}}$}"
    sw = "\\multicolumn{2}{c}{Under switching}"
    covs = "\\multicolumn{2}{c}{Hessian} & \\multicolumn{2}{c}{Sandwich}"
    titles = lead + ["$\\hat R$", "$p$", "Side", "$p$", "Side", "$\\hat R^{\\text{sw}}$",
                     "95\\% interval"]
    return (" & " * n + wald + " & " + sw + " \\\\\n"
            + f"\\cmidrule(lr){{{n + 1}-{n + 4}}}\\cmidrule(l){{{n + 5}-{n + 6}}}\n"
            + " & " * n + covs + " & & simulated, sandwich \\\\\n"
            + f"\\cmidrule(lr){{{n + 1}-{n + 2}}}\\cmidrule(lr){{{n + 3}-{n + 4}}}\n"
            + " & ".join(titles) + " \\\\")


#: Short labels for the upper-tail variants, so the sensitivity table fits the
#: text width.
VARIANT_LABELS_SHORT = {
    "baseline": "Unchanged",
    "replace_max": "Max.\\ $\\to$ 2nd largest",
    "drop_max": "Max.\\ deleted",
    "winsorise_top1": "Upper 1\\% winsorised",
}


def _cells(rec: dict) -> str:
    """R, the Wald test under each covariance, and R^sw with its simulated interval."""
    ratio = rec.get("ratio", rec.get("half_life_ratio"))
    cells = [f"{ratio:.2f}"]
    for cov in COVS:
        wald = rec["inference"][cov]["ratio_wald"]
        cells += [fmt_p(wald["p"]), fmt_side(wald["significance"])]
    sim = rec["inference"]["robust"]["ratio_switching_sim"]["ci95"]
    cells += [fmt_num(rec["ratio_switching_interp"], 2), fmt_sim(sim)]
    return " & ".join(cells)


#: The comment block shared by table8b and table9b.
_ROW_NOTES = (
    "% R = tau_calm / tau_stressed (regimes by sigma2 ascending). p is the two-sided\n"
    "% p-value of the Wald test of phi_calm = phi_stressed, and side its verdict at 5%:\n"
    "% R = 1 exactly when the two coefficients are equal, so the test needs no delta step.\n"
    "% R^sw is the ratio of the interpolated hours at which e_k'(P o Phi)^h 1 falls to\n"
    "% one half; it takes the same verdict (p_cc + p_ss - 1 > 0 significantly in every\n"
    "% fit). Its 95% interval is simulated from the sandwich covariance of\n"
    "% (p[0->0], p[1->0], phi_0, phi_1), 50,000 draws, the probabilities on the logit\n"
    "% scale. A draw whose expected path does not halve within 10,000 hours has an\n"
    "% unbounded half-life, which puts R^sw at zero (stressed) or infinity (calm): an\n"
    "% interval end at 0.00 or an open upper end comes from such draws.\n"
)


def _rolling(oos: dict) -> str:
    p = oos.get("protocol", {})
    rows = [f"{_day(pd.Timestamp(rec['mid']))} & {_cells(rec)} \\\\" for rec in oos["rolling"]]
    return (
        _BANNER
        + f"% Rolling MS-AR on the premium series: window {p.get('window')} h, "
          f"step {p.get('step')} h, {p.get('n_starts')} starts per fit.\n"
        + _ROW_NOTES
        + "% Source: output/oos_robustness.json.\n"
        + "\\begin{tabular}{@{}lrrcrcrl@{}}\n\\toprule\n"
        + _row_header(["Window mid"]) + "\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n"
    )


def _sensitivity(oos: dict, diag: dict, dates=None) -> str:
    if dates is None:
        dates = injection_dates(oos)
    sub = msar_block(diag, "sub-sample")
    sub = dict(sub, T=int(sub["n_obs"]) + 1)

    def t(n):
        return f"{n:,}".replace(",", "{,}")

    def row(label, rec):
        return f"{label} & {t(rec['T'])} & {_cells(rec)} \\\\"

    def panel(title):
        return f"\\multicolumn{{9}}{{l}}{{\\emph{{{title}}}}} \\\\"

    later = oos["injection"][0]
    rows = [panel("Estimation window, upper tail changed")]
    rows += [row(VARIANT_LABELS_SHORT[r["variant"]], r) for r in oos["sensitivity"]]
    rows += ["\\addlinespace", panel("Other windows"),
             row("Hourly sub-period", sub),
             row("Whole series", oos["extended_window"]),
             row("Later window", later),
             "\\addlinespace",
             panel("Later window, one hour set to the October maximum")]
    rows += [row(f"At {_day(d)}", r) for d, r in zip(dates, oos["injection"][1:])]
    return (
        _BANNER
        + "% Upper-tail variants of the paper window (T = 5,001), the hourly sub-period\n"
          "% (diagnostics.json), the whole series and the later window (oos_robustness.json),\n"
          "% and the later window with one hour overwritten. Columns as in table8b.\n"
        + _ROW_NOTES
        + "\\begin{tabular}{@{}lrrrcrcrl@{}}\n\\toprule\n"
        + _row_header(["Series", "$T$"]) + "\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n"
    )


TABLES = ("table3b_funding_robust", "table8b_rolling_robust", "table9b_sensitivity_robust")


def render(name: str, diag: dict, oos: dict) -> str:
    """The LaTeX source of one of ``TABLES``."""
    if name == "table3b_funding_robust":
        return _funding(diag, paper_window_times())
    if name == "table8b_rolling_robust":
        return _rolling(oos)
    if name == "table9b_sensitivity_robust":
        return _sensitivity(oos, diag)
    raise KeyError(name)


def write_tables(diag: dict, oos: dict, dests=None) -> list:
    """Write every table to ``<dest>/tables/`` for each destination directory."""
    dests = dests or (DEFAULT_OUT, REPO_ROOT / "paper")
    out = []
    for name in TABLES:
        text = render(name, diag, oos)
        for dest in dests:
            path = pathlib.Path(dest) / "tables" / f"{name}.tex"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            out.append(path)
    return out


