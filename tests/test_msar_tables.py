def _data_rows(text):
    """The body rows of a table8b/table9b rendering, split into cells."""
    body = text.split("\\midrule\n", 1)[1].split("\\bottomrule", 1)[0]
    return [[c.strip() for c in ln.rstrip(" \\").split(" & ")] for ln in body.splitlines()
            if " & " in ln]


class TestRollingTable:
    def test_one_row_per_window(self, artifacts):
        text = mt.render("table8b_rolling_robust", *artifacts)
        rows = [ln for ln in text.splitlines()
                if ln.split(" & ")[0].endswith((" 2025", " 2026"))]
        assert len(rows) == 14
        # dates as the text and the other tables write them
        assert rows[0] == ("23 Nov 2025 & 39.17 & $<$0.001 & $>1$ & 0.23 & n.s. & 1.90 & "
                           "[0.00, 5.60] \\\\")
        assert rows[4].startswith("6 Feb 2026 & ")

    def test_every_side_mark_is_the_wald_verdict(self, artifacts):
        diag, oos = artifacts
        rows = _data_rows(mt.render("table8b_rolling_robust", diag, oos))
        assert len(rows) == 14
        for cells, rec in zip(rows, oos["rolling"]):
            for col, cov in ((3, "hessian"), (5, "robust")):
                wald = rec["inference"][cov]["ratio_wald"]
                assert cells[col] == mt.fmt_side(wald["significance"])
                assert cells[col - 1] == mt.fmt_p(wald["p"])


class TestSensitivityTable:
    def test_three_panels_and_ten_rows(self, artifacts):
        text = mt.render("table9b_sensitivity_robust", *artifacts)
        assert text.count("\\multicolumn{9}{l}{\\emph{") == 3
        assert sum(ln.rstrip().endswith("\\\\") and "&" in ln
                   for ln in text.splitlines()) == 13       # three header lines + 10 rows

    def test_the_first_panel_names_the_estimation_window(self, artifacts):
        text = mt.render("table9b_sensitivity_robust", *artifacts)
        assert "\\emph{Estimation window, upper tail changed}" in text
        assert "aper window" not in text.split("\\begin{tabular}")[1]

    def test_the_headline_row(self, artifacts):
        text = mt.render("table9b_sensitivity_robust", *artifacts)
        assert "Unchanged & 5{,}001 & 11.19 & $<$0.001 & $>1$ & 0.31 & n.s. & 1.51 & " \
               "[0.00, 3.14] \\\\" in text

    def test_every_side_mark_is_the_wald_verdict(self, artifacts):
        diag, oos = artifacts
        rows = [r for r in _data_rows(mt.render("table9b_sensitivity_robust", diag, oos))
                if len(r) == 9]
        sub = mt.msar_block(diag, "sub-sample")
        recs = (oos["sensitivity"] + [sub, oos["extended_window"], oos["injection"][0]]
                + oos["injection"][1:])
        assert len(rows) == len(recs) == 10
        for cells, rec in zip(rows, recs):
            for col, cov in ((4, "hessian"), (6, "robust")):
                wald = rec["inference"][cov]["ratio_wald"]
                assert cells[col] == mt.fmt_side(wald["significance"])

    def test_the_wald_columns_share_one_header(self, artifacts):
        for name in ("table8b_rolling_robust", "table9b_sensitivity_robust"):
            text = mt.render(name, *artifacts)
            assert "Wald test of $\\phi_{\\text{calm}} = \\phi_{\\text{stressed}}$" in text
            assert "& Side &" in text and "& side &" not in text
            assert "\\multicolumn{2}{c}{Hessian} & \\multicolumn{2}{c}{Sandwich}" in text
            assert "\\cmidrule" in text
            assert "log scale" not in text      # no verdict rests on the log-scale form
            # the interval column says it is simulated under the sandwich
            assert "simulated, sandwich" in text and "95\\% interval" in text


class TestNumbersSheet:
    @pytest.fixture(scope="class")
    def rows(self, artifacts):
        diag, oos = artifacts
        return mt.sheet_rows(oos, diag)

    def test_every_fit_is_listed_once(self, rows):
        assert len(rows) == 25          # 2 + whole + later + 14 rolling + 4 + 3
        assert len({r["label"] for r in rows}) == 25

    def test_the_two_records_of_the_paper_window_agree(self, rows):
        """diagnostics.json and the sensitivity baseline hold the same fit."""
        paper = rows[0]
        base = next(r for r in rows if r["label"] == "sensitivity baseline")
        assert paper["ratio"] == pytest.approx(base["ratio"], rel=1e-9)
        assert paper["ratio_switching"] == base["ratio_switching"]
        for cov in mt.COVS:
            assert paper[cov] == base[cov]

    def test_the_text_sheet_has_a_line_per_fit(self, rows):
        assert len(mt.format_sheet(rows).splitlines()) == 25 + 2

    def test_the_sheet_carries_the_wald_verdicts(self, rows):
        paper = rows[0]
        assert paper["hessian_wald"]["side"] == "above"
        assert paper["robust_wald"]["side"] == "ns"
        assert round(paper["robust_wald"]["z"], 2) == 1.01
        for r in rows:
            for cov in mt.COVS:
                assert r[f"{cov}_switching_side"] == r[f"{cov}_wald"]["side"]
