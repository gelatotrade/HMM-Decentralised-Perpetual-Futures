"""The switching-aware MS-AR tables: formatting, and agreement with the artifacts.

``regime_engine.msar_tables`` renders table3b_funding_robust, table8b_rolling_robust
and table9b_sensitivity_robust from output/diagnostics.json and
output/oos_robustness.json. The shipped copies in output/tables/ and
paper/tables/ must be exactly what the renderer produces from the shipped
artifacts, so a regenerated artifact cannot drift from the tables beside it.
"""
import json
import pathlib

import pytest

from regime_engine import msar_tables as mt
from regime_engine.paths import DEFAULT_OUT, repo_root


class TestFormatting:
    def test_a_bounded_set(self):
        assert mt.fmt_set({"shape": "bounded", "bounds": [1.2144, 103.066]}) == "[1.21, 103.07]"

    def test_a_negative_end_keeps_its_sign(self):
        assert mt.fmt_set({"shape": "bounded", "bounds": [-13.655224627, 36.031]}) == \
            "[$-13.66$, 36.03]"

    def test_a_bound_that_rounds_to_unity_shows_a_third_decimal(self):
        """[0.05, 1.00] beside a "<1" verdict would read as a contradiction."""
        assert mt.fmt_set({"shape": "bounded", "bounds": [0.0512, 0.99872]}) == "[0.05, 0.999]"
        assert mt.fmt_set({"shape": "bounded", "bounds": [1.0, 2.0]}) == "[1.00, 2.00]"

    def test_two_rays(self):
        assert mt.fmt_set({"shape": "two_rays", "bounds": [-5.0, 3.0]}) == \
            "$(-\\infty, -5.00] \\cup [3.00, \\infty)$"

    def test_the_whole_line(self):
        assert mt.fmt_set({"shape": "whole_line", "bounds": [None, None]}) == \
            "$(-\\infty, \\infty)$"

    def test_an_undefined_set(self):
        assert mt.fmt_set({"shape": "undefined", "bounds": [None, None]}) == "--"

    @pytest.mark.parametrize("sig, mark", [("above", "$>1$"), ("below", "$<1$"),
                                           ("ns", "n.s."), ("undetermined", "--")])
    def test_side_markers(self, sig, mark):
        assert mt.fmt_side(sig) == mark

    def test_a_half_life_interval_open_above(self):
        assert mt.fmt_hl_ci([0.9064, None]) == "[0.91, $\\infty$)"
        assert mt.fmt_hl_ci([20.716, 121.013]) == "[20.7, 121.0]"

    def test_a_number_with_a_typographic_minus(self):
        assert mt.fmt_num(-2.7832, 2) == "$-2.78$"
        assert mt.fmt_num(0.97417, 3) == "0.974"
        assert mt.fmt_num(None, 2) == "--"

    @pytest.mark.parametrize("p, text", [(0.0002, "$<$0.001"), (0.0012, "0.001"),
                                         (0.0354, "0.035"), (0.0506, "0.051"),
                                         (0.0931, "0.093"), (0.0996, "0.10"),
                                         (0.3117, "0.31"), (None, "--")])
    def test_p_values(self, p, text):
        assert mt.fmt_p(p) == text

    def test_a_simulated_interval(self):
        assert mt.fmt_sim([0.7718, 8.0735]) == "[0.77, 8.07]"
        assert mt.fmt_sim([0.77, None]) == "[0.77, $\\infty$)"
        assert mt.fmt_sim([None, None]) == "--"


