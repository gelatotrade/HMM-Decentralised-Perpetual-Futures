@pytest.fixture(scope="module")
def artifacts():
    diag_path = pathlib.Path(DEFAULT_OUT) / "diagnostics.json"
    oos_path = pathlib.Path(DEFAULT_OUT) / "oos_robustness.json"
    if not (diag_path.exists() and oos_path.exists()):        # pragma: no cover
        pytest.skip("run the diagnostics and oos modules first")
    return json.loads(diag_path.read_text()), json.loads(oos_path.read_text())


TABLES = ("table3b_funding_robust", "table8b_rolling_robust", "table9b_sensitivity_robust")


@pytest.mark.parametrize("name", TABLES)
def test_shipped_copies_are_what_the_renderer_produces(artifacts, name):
    text = mt.render(name, *artifacts)
    assert (repo_root() / "paper" / "tables" / f"{name}.tex").read_text() == text
    assert (pathlib.Path(DEFAULT_OUT) / "tables" / f"{name}.tex").read_text() == text


@pytest.mark.parametrize("name", TABLES)
def test_tables_are_booktabs_tabulars(artifacts, name):
    text = mt.render(name, *artifacts)
    assert text.startswith("% Generated by regime_engine.msar_tables")
    assert "\\begin{tabular}" in text and text.rstrip().endswith("\\end{tabular}")
    assert "\\toprule" in text and "\\bottomrule" in text
    assert "None" not in text and "nan" not in text


