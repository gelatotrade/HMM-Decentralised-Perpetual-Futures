def test_the_paper_folders_hold_only_what_the_paper_inputs():
    assert sorted(INPUTS) == sorted(p.name for p in (PAPER / "tables").iterdir())
    assert sorted(GRAPHICS) == sorted(p.name for p in (PAPER / "figures").iterdir())


@pytest.mark.parametrize("name", sorted(set(INPUTS) - HAND))
def test_a_generated_table_is_the_copy_the_code_writes(name):
    printed = (PAPER / "tables" / name).read_text()
    assert printed.startswith("% Generated by regime_engine.")
    assert printed == (DEFAULT_OUT / "tables" / name).read_text()


def test_every_hand_kept_table_says_where_its_numbers_come_from():
    for name in HAND:
        head = (PAPER / "tables" / name).read_text().splitlines()[0]
        assert head.startswith(("% Manuscript copy.", "% Compact rendering of")), name


def test_the_return_model_table_is_the_archived_fit_with_bootstrap_errors():
    """Points: the archived full-window fit, re-indexed by sigma; errors: the bootstrap."""
    full = _load("summary_FULLSAMPLE_2025-10-02_to_2026-04-28.json")["return_K3"]
    boot = _load("bootstrap_hmm.json")["full_sample"]["sigma_ascending"]
    tab = _squash((PAPER / "tables" / "table2_regime_params.tex").read_text())
    order = sorted(range(3), key=lambda i: full["sigma_bps_per_hour"][i])
    for k, (i, name) in enumerate(zip(order, ("1 low", "2 moderate", "3 high"))):
        point = (full["mu_bps_per_hour"][i], full["sigma_bps_per_hour"][i],
                 full["annualised_vol_pct"][i], full["diag_A"][i],
                 full["expected_duration_hours"][i])
        cells = (boot["mu_bps_per_hour"][k], boot["sigma_bps_per_hour"][k],
                 boot["annualised_sigma_pct"][k], boot["A"][k][k],
                 boot["expected_duration_hours"][k])
        assert [c["point"] for c in cells] == pytest.approx(point, rel=1e-9)
        se = [c["se"] for c in cells]
        row = (f"{name} & ${point[0]:.3f}$ & ${point[1]:.2f}$ & ${point[2]:.1f}\\%$ & "
               f"${point[3]:.4f}$ & ${point[4]:.1f}$ \\\\ & $({se[0]:.2f})$ & "
               f"$({se[1]:.2f})$ & $({se[2]:.2f})$ & $({se[3]:.4f})$ & $({se[4]:.2f})$ \\\\")
        assert row in tab, row


def _p(p: float, digits: int | None = None) -> str:
    if p < 1e-4:
        return "$<$0.0001"
    if digits is None:
        digits = 4 if p < 0.01 else 3 if p < 0.1 else 2
    return f"{p:.{digits}f}"


def _thousands(x: float, fmt: str) -> str:
    return format(x, fmt).replace(",", "{,}")


@pytest.mark.parametrize("label,index,lags", [("Raw log-returns", 0, (0, 1)),
                                              ("\\MSAR(1), estimation window", 4, (0, 2))])
def test_the_diagnostics_table_rows_for_returns_and_the_premium_model(label, index, lags):
    """The HMM rows are pinned in test_manuscript_hmm_agreement."""
    t = _load("diagnostics.json")["tests"][index]
    tab = _squash((PAPER / "tables" / "table6_diagnostics.tex").read_text())
    for row, i in enumerate(lags):
        cells = [t[block][i] for block in ("ljung_box_z", "ljung_box_z2", "ljung_box_abs_z")]
        stats = " & ".join(f"{_thousands(c['Q'], ',.1f')} [{_p(c['p'])}]" for c in cells)
        lead = label if row == 0 else ""
        assert _squash(f"{lead} & {cells[0]['lag']} & {stats} \\\\") in tab, (label, i)
    a, jb = t["arch_lm"], t["jarque_bera"]
    skew = f"${jb['skew']:.2f}$" if jb["skew"] < 0 else f"{jb['skew']:.2f}"
    row = (f"{label} & {a['LM']:.1f} [{_p(a['p'], 4)}] & {_thousands(jb['JB'], ',.0f')} "
           f"[{_p(jb['p'], 4)}] & {skew} & {jb['excess_kurtosis']:.2f} \\\\")
    assert _squash(row) in tab, row


