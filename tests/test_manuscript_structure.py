def _pdf_strings(path) -> set:
    """Every hex-encoded UTF-16 string in the PDF's compressed object streams."""
    raw = path.read_bytes()
    found = set()
    for m in re.finditer(rb"stream\r?\n(.*?)\r?\nendstream", raw, re.S):
        try:
            data = zlib.decompress(m.group(1))
        except zlib.error:
            continue
        for h in re.findall(rb"<feff([0-9a-fA-F\s]*)>", data):
            found.add(bytes.fromhex(h.decode().replace("\n", "")).decode("utf-16-be"))
    return found


def _citation():
    """CITATION.cff, parsed; the checks that need it are kept apart, so that the
    others run where PyYAML is not installed."""
    yaml = pytest.importorskip("yaml")
    return yaml.safe_load((ROOT / "CITATION.cff").read_text())


def test_the_title_is_the_same_everywhere():
    title = TEX.split(r"\title{")[1].split(r"\author")[0]
    title = re.sub(r"\\(Large|large|bfseries)|\\\\(\[[^\]]*\])?", " ", title)
    assert _squash(title.rstrip().rstrip("}")) == TITLE
    assert f"pdftitle={{{TITLE}}}" in TEX
    assert TITLE in _pdf_strings(PAPER / "paper.pdf")
    readme = _squash((ROOT / "README.md").read_text().replace("> ", " ").replace("**", ""))
    assert TITLE in readme
    assert TITLE in (ROOT / "pyproject.toml").read_text()


def test_the_abstract_fits_the_ssrn_field_and_is_the_one_the_readme_carries():
    abstract = plain_abstract()
    assert len(abstract) <= SSRN_ABSTRACT_LIMIT, len(abstract)
    assert abstract.endswith("All results are descriptive.")
    quoted = [_squash(" ".join(line[2:] for line in block.splitlines()))
              for block in re.split(r"\n\s*\n", (ROOT / "README.md").read_text())
              if block.startswith("> ") and all(li.startswith(">") for li in block.splitlines())]
    assert abstract in quoted


def test_the_version_is_the_same_everywhere():
    import regime_engine
    assert regime_engine.__version__ == VERSION
    assert re.search(r'^version = "([^"]+)"', (ROOT / "pyproject.toml").read_text(),
                     re.M).group(1) == VERSION
    assert f"(version {VERSION})" in TEX


def test_the_citation_file_carries_the_title_abstract_and_version():
    import datetime
    cff = _citation()
    assert TITLE in cff["title"] and _squash(cff["preferred-citation"]["title"]) == TITLE
    assert _squash(cff["preferred-citation"]["abstract"]) == plain_abstract()
    assert str(cff["version"]) == VERSION
    # the release date agrees with the cited month and with the paper's date line
    released = datetime.date.fromisoformat(str(cff["date-released"]))
    cited = cff["preferred-citation"]
    assert (released.year, released.month) == (cited["year"], cited["month"])
    assert "\\date{" + released.strftime("%B %Y") + "}" in TEX
