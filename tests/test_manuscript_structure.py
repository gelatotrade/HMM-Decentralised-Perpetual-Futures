def test_every_citation_resolves_and_every_reference_is_cited():
    bib = TEX.split(r"\begin{thebibliography}")[1].split(r"\end{thebibliography}")[0]
    text = TEX.replace(bib, "") + "".join((PAPER / "tables" / n).read_text() for n in INPUTS)
    cited = set()
    for keys in re.findall(r"\\cite[a-z]*\*?(?:\[[^\]]*\])*\{([^}]*)\}", text):
        cited |= {k.strip() for k in keys.split(",")}
    items = re.findall(r"\\bibitem\[([^\]]*)\]\{([^}]*)\}", bib)
    keys = [k for _, k in items]
    assert len(keys) == len(set(keys))
    assert cited == set(keys)
    labels = [label for label, _ in items]
    assert len(labels) == len(set(labels)), "two references would print the same label"


