"""What the manuscript is built from: its tables, references, title, abstract and version.

A table the paper inputs is either generated, and then identical to the copy
the code writes to ``output/tables/``, or kept by hand from an archived fit, and
then pinned cell by cell here. ``paper/tables`` and ``paper/figures`` hold only
what the paper inputs. Every citation resolves and every reference is cited.
The title, the abstract and the version agree across the paper, its PDF, the
README, CITATION.cff and pyproject.toml.
"""
from __future__ import annotations

import json
import re
import zlib

import pytest

from regime_engine.paths import DEFAULT_OUT, repo_root

ROOT = repo_root()
PAPER = ROOT / "paper"
TEX = (PAPER / "paper.tex").read_text()
INPUTS = re.findall(r"\\input\{tables/([^}]+)\}", TEX)
GRAPHICS = [name for _, name in
            re.findall(r"\\includegraphics(\[[^\]]*\])?\{figures/([^}]+)\}", TEX)]
#: Tables kept by hand: the archived full-window fit, and compact renderings.
HAND = {"table2_regime_params.tex", "table5_robustness.tex", "table6_diagnostics.tex"}
TITLE = ("Same Formula, Different Signal: Funding-Rate Censoring and the Premium Gap "
         "between Hyperliquid and Centralised Perpetuals")
VERSION = "1.3.0"
SSRN_ABSTRACT_LIMIT = 1900


def _load(name):
    path = DEFAULT_OUT / name
    if not path.exists():                       # pragma: no cover
        pytest.skip(f"{name} has not been generated")
    return json.loads(path.read_text())


def _squash(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def plain_abstract(tex: str = TEX) -> str:
    """The abstract as it is pasted into a plain-text field."""
    a = tex.split(r"\begin{abstract}")[1].split(r"\medskip")[0].replace(r"\noindent", "")
    a = a.replace("~", " ").replace(r"\%", "%")
    a = re.sub(r"\$([^$]*)\$", r"\1", a)
    return _squash(a)


